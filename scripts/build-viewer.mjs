#!/usr/bin/env node
/**
 * Bundles dotpm's snapshot viewer (packages/viewer + packages/ui) from the pinned
 * vendor/obsidian-pm submodule into src/generated/, which is committed. Run it when bumping
 * the submodule:
 *
 *   git submodule update --init
 *   (cd vendor/obsidian-pm && npx pnpm install --frozen-lockfile --ignore-scripts)
 *   npm run build:viewer && npm run build
 */
import { build } from "esbuild";
import { execSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { dotpmAlias, dotpmNodePaths, vendorDir } from "./dotpm-paths.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "src/generated");
mkdirSync(out, { recursive: true });

const dotpmVersion = JSON.parse(readFileSync(join(vendorDir, "package.json"), "utf8")).version;
const dotpmCommit = execSync("git rev-parse --short HEAD", { cwd: vendorDir }).toString().trim();

// dotpm bundles every UI language. The page carries the catalog for the site's locale in its
// snapshot data, so the browser bundle keeps only English as the fallback.
const englishOnly = {
  name: "english-only",
  setup(b) {
    b.onResolve({ filter: /locales\/[^/]+\.json$/ }, (args) =>
      args.path.endsWith("/en.json") ? undefined : { path: args.path, namespace: "empty-locale" },
    );
    b.onLoad({ filter: /.*/, namespace: "empty-locale" }, () => ({
      contents: "{}",
      loader: "json",
    }));
  },
};

// The site changes a few of dotpm's viewer modules: the task table lists assignees by full
// name rather than initial bubbles, and sorts and collapses where dotpm's snapshot table is
// read-only. Each file in scripts/overrides/ stands in for dotpm's module of the same path,
// loaded with the original's directory so its imports resolve the same way. An override
// that builds on the original imports it as `dotpm-original:./<module>`.
const overrides = [
  { filter: /[\\/]cells[\\/]AssigneesCell\.ts$/, file: "scripts/overrides/AssigneesCell.ts" },
  { filter: /[\\/]views[\\/]snapshotTable\.ts$/, file: "scripts/overrides/snapshotTable.ts" },
];
const overrideModules = {
  name: "overrides",
  setup(b) {
    for (const { filter, file } of overrides) {
      b.onLoad({ filter, namespace: "file" }, (args) => ({
        contents: readFileSync(join(root, file), "utf8"),
        loader: "ts",
        resolveDir: dirname(args.path),
      }));
    }
    b.onResolve({ filter: /^dotpm-original:/ }, (args) => ({
      path: join(args.resolveDir, `${args.path.slice("dotpm-original:".length)}.ts`),
      namespace: "dotpm-original",
    }));
    b.onLoad({ filter: /.*/, namespace: "dotpm-original" }, (args) => ({
      contents: readFileSync(args.path, "utf8"),
      loader: "ts",
      resolveDir: dirname(args.path),
    }));
  },
};

const js = await build({
  entryPoints: [join(root, "scripts/viewer-entry.ts")],
  bundle: true,
  write: false,
  format: "esm",
  platform: "browser",
  target: "es2022",
  minify: true,
  legalComments: "none",
  nodePaths: dotpmNodePaths,
  alias: dotpmAlias,
  plugins: [englishOnly, overrideModules],
  // The viewer build defines this for dotpm's standalone HTML export, which is unused here.
  define: { __VIEWER_TEMPLATE__: '""' },
});

// Only the stylesheets the three read-only views use. The viewer's theme.css is left out:
// it styles html/body for a standalone page; src/components/styles/dotpm.scss maps the
// Obsidian variables these sheets read onto Quartz's theme instead.
const sheets = [
  "variables",
  "chrome",
  "view-header",
  "table",
  "gantt",
  "kanban",
  "widgets",
  "utilities",
];
const css = await build({
  stdin: {
    contents: sheets.map((name) => `@import "./${name}.css";`).join("\n"),
    resolveDir: join(vendorDir, "src/styles"),
    loader: "css",
  },
  bundle: true,
  write: false,
  minify: true,
});

const banner = `// Generated by scripts/build-viewer.mjs from dotpm ${dotpmVersion} (${dotpmCommit}). Do not edit.\n`;
const asModule = (text) => banner + `export default ${JSON.stringify(text)};\n`;
writeFileSync(join(out, "viewer-js.ts"), asModule(js.outputFiles[0].text));
writeFileSync(join(out, "viewer-css.ts"), asModule(css.outputFiles[0].text));
writeFileSync(
  join(out, "version.ts"),
  banner +
    `export const DOTPM_VERSION = ${JSON.stringify(dotpmVersion)};\n` +
    `export const DOTPM_COMMIT = ${JSON.stringify(dotpmCommit)};\n`,
);

const kb = (s) => `${(s.length / 1024).toFixed(0)} kB`;
console.log(
  `viewer ${kb(js.outputFiles[0].text)} js, ${kb(css.outputFiles[0].text)} css (dotpm ${dotpmVersion} @ ${dotpmCommit})`,
);
